// ===== 汇总导出 =====
export type GradeId = 'grade1-up' | 'grade1-down' | 'grade2-up' | 'grade2-down'
export type Subject = 'chinese' | 'math' | 'english'

export const allChapters: Record<GradeId, Record<Subject, Chapter[]>> = {
  'grade1-up': { chinese: chinese1up, math: math1up, english: english1up },
  'grade1-down': { chinese: chinese1down, math: math1down, english: english1down },
  'grade2-up': { chinese: chinese2up, math: math2up, english: english2up },
  'grade2-down': { chinese: chinese2down, math: math2down, english: english2down },
}

export function getChapters(grade: GradeId, subject: Subject): Chapter[] {
  return allChapters[grade]?.[subject] || []
}

export function getChapter(grade: GradeId, subject: Subject, chapterId: string): Chapter | undefined {
  return getChapters(grade, subject).find(c => c.id === chapterId)
}
